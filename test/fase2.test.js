test("перевод с Python: with остаётся в примечании, есть «с … как»", () => {
  const r2 = V.translateToPon("with open('a.txt') as f:\n    print(f.read())\n", "python");
  assert.match(r2.code, /с /);
  assert.match(r2.code, /как /);
  assert.ok((r2.notes || []).some((n) => /with/.test(n.text || n)), JSON.stringify(r2.notes));
});
test("перевод с Python: async/await и морж", () => {
  const a = V.translateToPon("async def f():\n    return await g()\n", "python");
  assert.match(a.code, /асинхронная функция f/);
  assert.match(a.code, /ждать /);
  const w = V.translateToPon("if (n := len(xs)) > 0:\n    print(n)\n", "python");
  assert.match(w.code, /:=/);
});
test("перевод из Понятного сохраняет новые конструкции", () => {
  const src = "пусть н = 0\nпусть x = (н := 3)\nпиши формат(\"%d\", x)\n";
  const js = IZ.translate(src, "javascript");
  assert.match(js.code, /н = 3|н := 3/);
});
