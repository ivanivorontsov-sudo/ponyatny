const test = require("node:test");
const assert = require("node:assert");
const Y = require("../src/yadro");
const V = require("../src/perevod-v");
const IZ = require("../src/perevod-iz");

const MODS = {
  "мат.pon": "функция факториал(н)\n    если н <= 1 то\n        верни 1\n    конец\n    верни н * факториал(н - 1)\nконец\n"
};
const resolve = (p) => {
  const name = String(p).replace(/^.*[/\\\\]/, "");
  const src = MODS[name] || MODS[p];
  if (!src) return null;
  return { id: name, name, source: src };
};
const r = (src, extra) => Y.run(src, Object.assign({ resolve }, extra || {}));
const fails = (src, re) => assert.throws(() => r(src), (e) => { assert.match(e.message, re); return true; });

test("метки и иди к: цикл", () => {
  assert.deepStrictEqual(r("пусть i = 0\nметка старт\ni += 1\nесли i < 3 то\n    иди к старт\nконец\nпиши i"), ["3"]);
});
test("метки: пропуск и синонимы", () => {
  assert.deepStrictEqual(r("пиши \"а\"\nиди к выход\nпиши \"б\"\nметка выход\nпиши \"в\""), ["а", "в"]);
  assert.deepStrictEqual(r("пиши \"а\"\nтелепортируйся к выход\nпиши \"б\"\nярлык выход\nпиши \"в\""), ["а", "в"]);
  assert.deepStrictEqual(r("пиши \"а\"\ngoto выход\nпиши \"б\"\nметка выход\nпиши \"в\""), ["а", "в"]);
});
test("метка конец запрещена как имя, переход к неизвестной — ошибка", () => {
  fails("метка конец\nпиши 1", /служебн|зарезерв|нельзя|ожидалось имя|конец/i);
  fails("иди к неттакой", /нет метки|неизвестн/i);
});

test("ссылки, разыменование и размер", () => {
  assert.deepStrictEqual(r("пусть x = 10\nпусть п = ссылка x\nпиши *п\n*п = 20\nпиши x, п.значение\nпиши размер(1), размер(истина), размер(\"аб\"), размер([1, 2])"), ["10", "20 20", "8 1 4 2"]);
  assert.deepStrictEqual(r("пусть x = 5\nпусть q = &x\nпиши *q\nq.значение = 9\nпиши x"), ["5", "9"]);
  assert.deepStrictEqual(r("пусть x = 3\nпусть п = указатель на x\nпиши *п, sizeof(x)"), ["3 8"]);
});

test("свойство получить и установить", () => {
  const src = "класс Прямоугольник\n    пусть ш = 0\n    пусть выс = 0\n    функция создать(ш, выс)\n        это.ш = ш\n        это.выс = выс\n    конец\n    свойство периметр\n        получить\n            верни 2 * (это.ш + это.выс)\n        конец\n        установить значение\n            пусть сторона = значение / 4\n            это.ш = сторона\n            это.выс = сторона\n        конец\n    конец\nконец\nпусть п = Прямоугольник(2, 4)\nпиши п.периметр\nп.периметр = 20\nпиши п.ш, п.выс";
  assert.deepStrictEqual(r(src), ["12", "5 5"]);
});

test("это(...) и родитель(...) , несколько создать", () => {
  const src = "класс Т\n    пусть а = 0\n    пусть б = 0\n    функция создать(а)\n        это.а = а\n        это.б = 0\n    конец\n    функция создать(а, б)\n        это(а)\n        это.б = б\n    конец\n    функция строкой()\n        верни строка(это.а) + \" \" + строка(это.б)\n    конец\nконец\nпиши Т(5)\nпиши Т(1, 2)";
  assert.deepStrictEqual(r(src), ["5 0", "1 2"]);
  const p = "класс А\n    функция создать(имя)\n        это.имя = имя\n    конец\nконец\nкласс Б наследует А\n    функция создать(имя)\n        родитель(имя)\n    конец\n    функция привет()\n        верни \"привет, \" + это.имя\n    конец\nконец\nпиши Б(\"Ваня\").привет()";
  assert.deepStrictEqual(r(p), ["привет, Ваня"]);
});

