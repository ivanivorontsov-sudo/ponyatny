test("опечатки в служебных словах прощаются с предупреждением", () => {
  const w = [];
  const out = Y.run("пуст x = 2\nнапишы x * 3\nесли x > 1 тo\nнапиши \"да\"\nконц\nповторить 2 рза\nнапиши 1\nконец", { warn: (x) => w.push(x) });
  assert.deepStrictEqual(out, ["6", "да", "1", "1"]);
  assert.strictEqual(w.length, 5);
  assert.ok(w.some((x) => /опечатка «пуст» исправлена на «пусть»/.test(x.text) && x.line === 1));
  assert.ok(w.some((x) => /латинские буквы.*понято как «то»/.test(x.text) && x.line === 3));
  assert.ok(w.some((x) => /«рза» исправлена на «раз»/.test(x.text)));
});
