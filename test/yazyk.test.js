  assert.deepStrictEqual(r("напиши [3, 1, 2].отсортировано(), [1, 2, 3].преобразуй(x => x * x), [1, 2, 3, 4].отфильтруй(функция(x) => x > 2), [1, 2, 3].свернуть(функция(а, б) => а + б, 0)"), ["[1, 2, 3] [1, 4, 9] [3, 4] 6"]);
