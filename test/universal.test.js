test("скомпилированная программа с выходом и потоком ошибок работает в Node.js", () => {
  const cp = require("child_process"), fs = require("fs"), os = require("os"), path = require("path");
  const f = path.join(os.tmpdir(), "pon-u-" + process.pid + ".js");
  fs.writeFileSync(f, Y.standalone(Y.compile("пиши \"до\"\nпредупреди \"ой\"\nвыход(3)\nпиши \"после\"")));
  const res = cp.spawnSync(process.execPath, [f], { encoding: "utf8" });
  fs.unlinkSync(f);
  assert.strictEqual(res.status, 3);
  assert.strictEqual(res.stdout, "до\n");
  assert.strictEqual(res.stderr, "ой\n");
});

